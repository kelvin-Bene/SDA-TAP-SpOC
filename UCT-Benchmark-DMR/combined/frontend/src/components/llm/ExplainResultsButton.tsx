import { useState } from 'react';
import { useMutation } from '@tanstack/react-query';
import { Sparkles, Loader2, AlertCircle } from 'lucide-react';
import {
  Dialog,
  DialogContent,
  DialogDescription,
  DialogHeader,
  DialogTitle,
  DialogTrigger,
} from '@/components/ui/dialog';
import { Button } from '@/components/ui/button';
import { api } from '@/api/client';
import { LlmMarkdown } from './LlmMarkdown';

interface ExplainResultsButtonProps {
  submissionId: string | number;
}

interface ExplainResponse {
  text: string;
}

/**
 * A2 — "Explain My Results" button + dialog.
 *
 * Renders next to the existing Download Report / CSV / Export JSON buttons
 * on ResultsPage. Click → opens a Radix Dialog with a spinner; the LLM call
 * fires lazily on dialog open (not on button click) so accidental clicks
 * don't burn LLM tokens.
 *
 * Phase 2 — DGX Spark local edition only. Cloud builds will get a 503/404
 * from the backend if anything triggers this; we render a friendly message
 * in that case.
 */
export function ExplainResultsButton({ submissionId }: ExplainResultsButtonProps) {
  const [open, setOpen] = useState(false);

  const mutation = useMutation({
    mutationFn: async () => {
      const id = typeof submissionId === 'string' ? parseInt(submissionId, 10) : submissionId;
      const response = await api.explainResults(id);
      return response.data as ExplainResponse;
    },
  });

  const handleOpenChange = (next: boolean) => {
    setOpen(next);
    // Fire the LLM call lazily on first open. Don't refetch on subsequent
    // re-opens unless the user explicitly hits "Regenerate".
    if (next && !mutation.data && !mutation.isPending && !mutation.isError) {
      mutation.mutate();
    }
  };

  const errorMessage = mutation.error
    ? formatError(mutation.error)
    : null;

  return (
    <Dialog open={open} onOpenChange={handleOpenChange}>
      <DialogTrigger asChild>
        <Button variant="outline" className="gap-2 border-cosmic-cyan/40 hover:bg-cosmic-cyan/10">
          <Sparkles className="h-4 w-4 text-cosmic-cyan" />
          Explain My Results
        </Button>
      </DialogTrigger>
      <DialogContent className="max-w-2xl">
        <DialogHeader>
          <DialogTitle className="flex items-center gap-2">
            <Sparkles className="h-5 w-5 text-cosmic-cyan" />
            AI Explanation
          </DialogTitle>
          <DialogDescription>
            Plain-English interpretation of your submission's metrics, generated by the local LLM.
          </DialogDescription>
        </DialogHeader>

        <div className="min-h-[200px] max-h-[60vh] overflow-y-auto">
          {mutation.isPending && (
            <div className="flex flex-col items-center justify-center py-12 gap-3">
              <Loader2 className="h-8 w-8 animate-spin text-cosmic-cyan" />
              <p className="text-sm text-muted-foreground">
                Local LLM is analyzing your submission...
              </p>
              <p className="text-xs text-muted-foreground">
                (this may take a few seconds on the Spark, longer on CPU)
              </p>
            </div>
          )}

          {errorMessage && !mutation.isPending && (
            <div className="flex items-start gap-3 rounded-md border border-destructive/40 bg-destructive/5 p-4">
              <AlertCircle className="h-5 w-5 text-destructive shrink-0 mt-0.5" />
              <div className="space-y-1">
                <p className="text-sm font-medium text-destructive">Could not generate explanation</p>
                <p className="text-sm text-muted-foreground">{errorMessage}</p>
              </div>
            </div>
          )}

          {mutation.data && !mutation.isPending && (
            <LlmMarkdown>{mutation.data.text}</LlmMarkdown>
          )}
        </div>

        <div className="flex items-center justify-between pt-2">
          <p className="text-xs text-muted-foreground">
            Generated by the local LLM. May contain inaccuracies — verify against the raw metrics.
          </p>
          {mutation.data && !mutation.isPending && (
            <Button
              variant="ghost"
              size="sm"
              onClick={() => {
                mutation.reset();
                mutation.mutate();
              }}
            >
              Regenerate
            </Button>
          )}
        </div>
      </DialogContent>
    </Dialog>
  );
}

function formatError(err: unknown): string {
  const axiosErr = err as {
    response?: { status?: number; data?: { detail?: string } };
    message?: string;
  };
  const status = axiosErr?.response?.status;

  if (status === 503) {
    return 'AI features are unavailable — the Ollama service is not running. Make sure the GPU compose profile is up: `docker compose --profile gpu up -d`';
  }
  if (status === 502) {
    return 'The local LLM server returned an error. Check the Ollama container logs.';
  }
  if (status === 404) {
    return 'AI features are not enabled on this build. Phase 2 LLM features require LOCAL_DGX_MODE=true.';
  }
  if (typeof axiosErr?.response?.data?.detail === 'string') {
    return axiosErr.response.data.detail;
  }
  return axiosErr?.message || 'Unknown error';
}
